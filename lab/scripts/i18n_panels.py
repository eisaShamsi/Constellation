def inject(locale: str, data: dict, t: dict) -> dict:
    """Inject panel keys into a locale dict."""
    # 1. Add section label to settings.sections
    data.setdefault('settings', {}).setdefault('sections', {})['panels'] = t['sectionLabel']

    # 2. Add settings.panels block
    data['settings']['panels'] = {
        'intro': t['intro'],
        'slotsHeading': t['slotsHeading'],
        'slotLeftOfNote': t['slotLeftOfNote'],
        'slotRightOfNote': t['slotRightOfNote'],
        'slotRightSidebar': t['slotRightSidebar'],
        'slotHidden': t['slotHidden'],
        'panelBacklinks': t['panelBacklinks'],
        'panelBacklinksDesc': t['panelBacklinksDesc'],
        'panelOutgoing': t['panelOutgoing'],
        'panelOutgoingDesc': t['panelOutgoingDesc'],
        'panelProperties': t['panelProperties'],
        'panelPropertiesDesc': t['panelPropertiesDesc'],
        'panelTags': t['panelTags'],
        'panelTagsDesc': t['panelTagsDesc'],
        'panelSky': t['panelSky'],
        'panelSkyDesc': t['panelSkyDesc'],
        'panelTasks': t['panelTasks'],
        'panelTasksDesc': t['panelTasksDesc'],
        'panelCalendar': t['panelCalendar'],
        'panelCalendarDesc': t['panelCalendarDesc'],
        'panelHealth': t['panelHealth'],
        'panelHealthDesc': t['panelHealthDesc'],
        'panelProvenance': t['panelProvenance'],
        'panelProvenanceDesc': t['panelProvenanceDesc'],
        'panelReview': t['panelReview'],
        'panelReviewDesc': t['panelReviewDesc'],
        'panelLinks': t['panelLinks'],
        'panelLinksDesc': t['panelLinksDesc'],
        'resetDefault': t['resetDefault'],
        'resetDefaultDesc': t['resetDefaultDesc'],
    }
    return data

errors = []
for locale, t in TRANSLATIONS.items():
    path = ROOT / f'{locale}.json'
    if not path.exists():
        errors.append(f'  MISSING: {path}')
        continue
    with open(path, encoding='utf-8') as f:
        data = json.load(f)
    data = inject(locale, data, t)
    with open(path, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
    print(f'  ✓ {locale}.json')

if errors:
    print('\nErrors:')
    for e in errors: print(e)
    sys.exit(1)
