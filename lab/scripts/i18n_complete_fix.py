def set_nested(d: dict, dotpath: str, value) -> None:
    """Set d[k1][k2]...[kN] = value, creating intermediate dicts."""
    keys = dotpath.split('.')
    for k in keys[:-1]:
        d = d.setdefault(k, {})
    d[keys[-1]] = value


def merge_missing(locale_data: dict, translations: dict) -> int:
    """Apply translations to locale_data where keys are absent. Returns count of keys added."""
    added = 0
    for dotpath, value in translations.items():
        # Navigate to check if the key exists
        parts = dotpath.split('.')
        node = locale_data
        exists = True
        for p in parts:
            if isinstance(node, dict) and p in node:
                node = node[p]
            else:
                exists = False
                break
        if not exists:
            set_nested(locale_data, dotpath, value)
            added += 1
    return added


